//
//  YouTubeCaptions.swift
//  leanring-buddy
//
//  A YouTube video's captions, read the way the watch page lists them.
//
//  How YouTube publishes captions. The watch page carries the player's
//  configuration as `ytInitialPlayerResponse`, and in it
//  `captions.playerCaptionsTracklistRenderer.captionTracks`: one entry per
//  track, each with a language, `kind: "asr"` when YouTube generated it
//  from the speech, and a signed `baseUrl` on /api/timedtext. Adding
//  `fmt=json3` to that address returns the lines as JSON, each with its
//  start in milliseconds.
//
//  What happens in practice (checked November 2026). The track list is
//  there for any video with captions, but the timedtext address now
//  carries `exp=xpe` and answers 200 with an empty body unless the request
//  also carries a proof-of-origin token that only YouTube's own player
//  script can make. Buddy does not imitate YouTube's player or its apps
//  to get around that. So this path works only when YouTube serves the
//  track plainly; otherwise the video is remembered as "captions withheld"
//  and lecture mode uses the transcript panel on the page, then the sound.
//
//  Nothing is sent but the video's id, and one page and one track are
//  fetched per video per session at most.
//

import Foundation

/// One caption track as the watch page lists it.
nonisolated struct YouTubeCaptionTrack: Equatable, Sendable {
    let baseURL: URL
    let languageCode: String
    let isAutoGenerated: Bool
    let displayName: String
}

nonisolated enum YouTubeTranscriptOutcome: Equatable, Sendable {
    case transcript(cues: [TimedTranscriptCue], track: YouTubeCaptionTrack)
    /// Live now: captions of a live stream are not published as tracks.
    case liveStream
    case noCaptions
    /// The track is listed but YouTube returned nothing for it.
    case captionsWithheld
    /// A consent page, a sign-in wall, a removed video, no network.
    case pageUnreadable(reason: String)

    /// For the log.
    var summary: String {
        switch self {
        case .transcript(let cues, let track):
            return "\(cues.count) lines, \(track.languageCode)\(track.isAutoGenerated ? " auto-generated" : "")"
        case .liveStream: return "live stream, no captions track"
        case .noCaptions: return "no captions"
        case .captionsWithheld: return "captions listed but withheld (proof-of-origin token required)"
        case .pageUnreadable(let reason): return "watch page unreadable: \(reason)"
        }
    }
}

nonisolated enum YouTubeCaptions {
    /// Fetches the watch page and the best track. Never throws: every way
    /// it can fail is an outcome lecture mode knows how to fall back from.
    static func fetchTranscript(videoIdentifier: String, preferredLanguageCodes: [String],
                                urlSession: URLSession = .shared) async -> YouTubeTranscriptOutcome {
        guard var watchPageComponents = URLComponents(string: "https://www.youtube.com/watch") else {
            return .pageUnreadable(reason: "bad address")
        }
        watchPageComponents.queryItems = [URLQueryItem(name: "v", value: videoIdentifier)]
        guard let watchPageURL = watchPageComponents.url else { return .pageUnreadable(reason: "bad address") }

        var watchPageRequest = URLRequest(url: watchPageURL, timeoutInterval: 6)
        watchPageRequest.setValue(acceptLanguageHeader(for: preferredLanguageCodes), forHTTPHeaderField: "Accept-Language")
        // Session cookies from Safari are not wanted here and none are sent.
        watchPageRequest.httpShouldHandleCookies = false

        let watchPageHTML: String
        do {
            let (data, response) = try await urlSession.data(for: watchPageRequest)
            guard (response as? HTTPURLResponse)?.statusCode == 200 else {
                return .pageUnreadable(reason: "status \((response as? HTTPURLResponse)?.statusCode ?? 0)")
            }
            watchPageHTML = String(decoding: data, as: UTF8.self)
        } catch {
            return .pageUnreadable(reason: error.localizedDescription)
        }

        guard let playerResponse = playerResponse(fromWatchPageHTML: watchPageHTML) else {
            return .pageUnreadable(reason: "no player configuration (consent or sign-in page)")
        }
        let videoDetails = playerResponse["videoDetails"] as? [String: Any] ?? [:]
        if (videoDetails["isLive"] as? Bool) == true { return .liveStream }

        let tracks = captionTracks(fromPlayerResponse: playerResponse)
        let defaultTrackIndex = defaultCaptionTrackIndex(fromPlayerResponse: playerResponse)
        guard let chosenTrack = chooseTrack(from: tracks, defaultTrackIndex: defaultTrackIndex,
                                            preferredLanguageCodes: preferredLanguageCodes) else {
            return .noCaptions
        }

        guard var trackComponents = URLComponents(url: chosenTrack.baseURL, resolvingAgainstBaseURL: false) else {
            return .noCaptions
        }
        var trackQueryItems = (trackComponents.queryItems ?? []).filter { $0.name != "fmt" }
        trackQueryItems.append(URLQueryItem(name: "fmt", value: "json3"))
        trackComponents.queryItems = trackQueryItems
        guard let trackURL = trackComponents.url else { return .noCaptions }

        var trackRequest = URLRequest(url: trackURL, timeoutInterval: 6)
        trackRequest.httpShouldHandleCookies = false
        do {
            let (data, response) = try await urlSession.data(for: trackRequest)
            guard (response as? HTTPURLResponse)?.statusCode == 200 else { return .captionsWithheld }
            let cues = cues(fromJSON3: data)
            return cues.isEmpty ? .captionsWithheld : .transcript(cues: cues, track: chosenTrack)
        } catch {
            return .pageUnreadable(reason: error.localizedDescription)
        }
    }

    private static func acceptLanguageHeader(for preferredLanguageCodes: [String]) -> String {
        var languages = preferredLanguageCodes
        if !languages.contains(where: { $0.hasPrefix("en") }) { languages.append("en") }
        return languages.enumerated().map { index, code in
            index == 0 ? code : "\(code);q=\(String(format: "%.1f", max(0.1, 1.0 - Double(index) * 0.1)))"
        }.joined(separator: ",")
    }

    /// The `ytInitialPlayerResponse` object in the page's script. Found by
    /// matching braces outside strings, since the JSON is followed by more
    /// script on the same line. Every assignment is tried, because the
    /// mobile page (where a request that is not from a desktop browser is
    /// sent) first sets it to null and fills it in later.
    static func playerResponse(fromWatchPageHTML watchPageHTML: String) -> [String: Any]? {
        var searchStart = watchPageHTML.startIndex
        while let markerRange = watchPageHTML.range(of: "ytInitialPlayerResponse = ", range: searchStart..<watchPageHTML.endIndex) {
            searchStart = markerRange.upperBound
            guard watchPageHTML[markerRange.upperBound...].first == "{" else { continue }
            let utf8Bytes = Array(watchPageHTML.utf8[markerRange.upperBound...])
            guard let objectBytes = balancedJSONObjectBytes(startingIn: utf8Bytes),
                  let playerResponse = (try? JSONSerialization.jsonObject(with: Data(objectBytes))) as? [String: Any] else { continue }
            return playerResponse
        }
        return nil
    }

    private static func balancedJSONObjectBytes(startingIn bytes: [UInt8]) -> ArraySlice<UInt8>? {
        let openBrace = UInt8(ascii: "{"), closeBrace = UInt8(ascii: "}")
        let quote = UInt8(ascii: "\""), backslash = UInt8(ascii: "\\")
        guard bytes.first == openBrace else { return nil }
        let startIndex = bytes.startIndex
        var depth = 0
        var isInsideString = false
        var previousWasEscape = false
        var index = startIndex
        while index < bytes.count {
            let byte = bytes[index]
            if isInsideString {
                if previousWasEscape { previousWasEscape = false }
                else if byte == backslash { previousWasEscape = true }
                else if byte == quote { isInsideString = false }
            } else if byte == quote {
                isInsideString = true
            } else if byte == openBrace {
                depth += 1
            } else if byte == closeBrace {
                depth -= 1
                if depth == 0 { return bytes[startIndex...index] }
            }
            index += 1
        }
        return nil
    }

    static func captionTracks(fromPlayerResponse playerResponse: [String: Any]) -> [YouTubeCaptionTrack] {
        let captions = playerResponse["captions"] as? [String: Any]
        let tracklist = captions?["playerCaptionsTracklistRenderer"] as? [String: Any]
        let rawTracks = tracklist?["captionTracks"] as? [[String: Any]] ?? []
        return rawTracks.compactMap { rawTrack in
            guard let baseURLText = rawTrack["baseUrl"] as? String,
                  let baseURL = URL(string: baseURLText.hasPrefix("/") ? "https://www.youtube.com" + baseURLText : baseURLText),
                  let languageCode = rawTrack["languageCode"] as? String else { return nil }
            let nameObject = rawTrack["name"] as? [String: Any]
            let displayName = nameObject?["simpleText"] as? String
                ?? ((nameObject?["runs"] as? [[String: Any]])?.compactMap { $0["text"] as? String }.joined())
                ?? languageCode
            return YouTubeCaptionTrack(baseURL: baseURL, languageCode: languageCode,
                                       isAutoGenerated: (rawTrack["kind"] as? String) == "asr", displayName: displayName)
        }
    }

    private static func defaultCaptionTrackIndex(fromPlayerResponse playerResponse: [String: Any]) -> Int? {
        let captions = playerResponse["captions"] as? [String: Any]
        let tracklist = captions?["playerCaptionsTracklistRenderer"] as? [String: Any]
        let audioTracks = tracklist?["audioTracks"] as? [[String: Any]]
        return audioTracks?.first?["defaultCaptionTrackIndex"] as? Int
    }

    /// The words as spoken. The auto-generated track is in the language the
    /// lecturer speaks, so a human track in that language is best, then the
    /// auto-generated one, then whatever YouTube would show by default, then
    /// a human track in the student's language, then anything.
    static func chooseTrack(from tracks: [YouTubeCaptionTrack], defaultTrackIndex: Int?,
                            preferredLanguageCodes: [String]) -> YouTubeCaptionTrack? {
        func baseLanguage(_ code: String) -> String { String(code.lowercased().split(separator: "-").first ?? "") }
        let humanTracks = tracks.filter { !$0.isAutoGenerated }
        if let autoGeneratedTrack = tracks.first(where: \.isAutoGenerated) {
            let spokenLanguage = baseLanguage(autoGeneratedTrack.languageCode)
            if let humanTrackInSpokenLanguage = humanTracks.first(where: { baseLanguage($0.languageCode) == spokenLanguage }) {
                return humanTrackInSpokenLanguage
            }
            return autoGeneratedTrack
        }
        if let defaultTrackIndex, tracks.indices.contains(defaultTrackIndex) { return tracks[defaultTrackIndex] }
        for preferredCode in preferredLanguageCodes.map(baseLanguage) {
            if let match = humanTracks.first(where: { baseLanguage($0.languageCode) == preferredCode }) { return match }
        }
        return humanTracks.first ?? tracks.first
    }

    /// Lines from a json3 track: `events`, each with `tStartMs` and `segs`
    /// of `utf8` text. Events holding only a line break are layout, not words.
    static func cues(fromJSON3 data: Data) -> [TimedTranscriptCue] {
        guard !data.isEmpty,
              let root = (try? JSONSerialization.jsonObject(with: data)) as? [String: Any],
              let events = root["events"] as? [[String: Any]] else { return [] }
        var cues: [TimedTranscriptCue] = []
        for event in events {
            guard let startMilliseconds = (event["tStartMs"] as? NSNumber)?.doubleValue,
                  let segments = event["segs"] as? [[String: Any]] else { continue }
            let eventText = segments.compactMap { $0["utf8"] as? String }.joined()
                .replacingOccurrences(of: "\n", with: " ")
                .trimmingCharacters(in: .whitespacesAndNewlines)
            guard !eventText.isEmpty else { continue }
            cues.append(TimedTranscriptCue(startSeconds: startMilliseconds / 1000, text: eventText))
        }
        return cues
    }
}

/// Each video's outcome, kept for the session only, so a second question
/// about the same video costs no request at all.
actor YouTubeTranscriptCache {
    private var outcomesByVideoIdentifier: [String: YouTubeTranscriptOutcome] = [:]
    private var fetchesInFlight: [String: Task<YouTubeTranscriptOutcome, Never>] = [:]

    func transcript(forVideoIdentifier videoIdentifier: String, preferredLanguageCodes: [String]) async -> YouTubeTranscriptOutcome {
        if let cachedOutcome = outcomesByVideoIdentifier[videoIdentifier] { return cachedOutcome }
        if let fetchInFlight = fetchesInFlight[videoIdentifier] { return await fetchInFlight.value }
        let fetch = Task {
            await YouTubeCaptions.fetchTranscript(videoIdentifier: videoIdentifier, preferredLanguageCodes: preferredLanguageCodes)
        }
        fetchesInFlight[videoIdentifier] = fetch
        let outcome = await fetch.value
        fetchesInFlight[videoIdentifier] = nil
        // A network failure is worth trying again on the next question;
        // everything else is a fact about the video for this session.
        if case .pageUnreadable = outcome {} else { outcomesByVideoIdentifier[videoIdentifier] = outcome }
        return outcome
    }
}
